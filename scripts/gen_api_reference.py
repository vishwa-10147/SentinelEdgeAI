#!/usr/bin/env python3
"""Generate docs/API.md from the live route table and the role table used by the tests.

    python scripts/gen_api_reference.py            # writes docs/API.md
    python scripts/gen_api_reference.py --check    # exit 1 if docs/API.md is out of date
"""
import argparse
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, ROOT)
os.environ.setdefault('SENTINEL_AUTH_DB', ':memory:')

SECTIONS = [
    ('Sign-in and account', ('/api/auth',)),
    ('Users and API tokens', ('/api/users', '/api/tokens')),
    ('Detections and devices', ('/api/alerts', '/api/live_stats', '/api/device', '/api/devices', '/api/flows',
                                '/api/risk_timeline', '/api/incidents', '/api/health')),
    ('Firewall and response', ('/api/firewall', '/api/playbook', '/api/policy', '/api/enforcement')),
    ('Models and evaluation', ('/api/models', '/api/eval')),
    ('Two-node mode', ('/api/brain', '/api/sensor')),
    ('Integrations, intelligence and reports', ('/api/integrations', '/api/intel', '/api/reports', '/api/export')),
    ('Administration', ('/api/setup', '/api/audit', '/api/demo')),
    ('Other', ('',)),
]


def build():
    from fastapi.routing import APIRoute
    import dashboard.dashboard_api as api
    from tests.test_endpoint_roles import ROUTES
    rows = []
    for route in api.app.routes:
        if not isinstance(route, APIRoute):
            continue
        for method in sorted(route.methods - {'HEAD'}):
            role = ROUTES.get((method, route.path), '?')
            doc = (route.endpoint.__doc__ or '').strip().splitlines()
            rows.append((route.path, method, role, doc[0] if doc else ''))
    out = ['# SentinelEdgeAI API reference', '',
           'Generated by `scripts/gen_api_reference.py` from the running route table; the minimum role of every '
           'endpoint is enforced and tested in `tests/test_endpoint_roles.py`.', '',
           'Authentication: `Authorization: Bearer <console access token | sak1 API token>` or `X-API-Key: <key>`. '
           'Roles: Viewer < Analyst < Operator < Admin. All responses carry the security headers described in SECURITY.md. '
           'Rate limits: 600 reads and 60 writes per client per minute.', '']
    used = set()
    for title, prefixes in SECTIONS:
        section = [r for r in rows if r not in used and any(r[0].startswith(p) for p in prefixes)]
        if not section:
            continue
        used.update(section)
        out += [f'## {title}', '', '| Method | Path | Minimum role | Notes |', '|---|---|---|---|']
        out += [f'| `{m}` | `{p}` | {role} | {doc} |' for p, m, role, doc in sorted(section, key=lambda r: (r[0], r[1]))]
        out.append('')
    return '\n'.join(out)


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    import logging
    logging.disable(logging.WARNING)
    text = build()
    path = os.path.join(ROOT, 'docs', 'API.md')
    if args.check:
        current = open(path).read() if os.path.exists(path) else ''
        if current != text:
            print('docs/API.md is out of date; run python scripts/gen_api_reference.py', file=sys.stderr)
            return 1
        return 0
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)
    print(f'wrote {path}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
